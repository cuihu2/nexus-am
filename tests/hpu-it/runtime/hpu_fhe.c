int hpu_fhe_resolve_generated_program(hpu_case_kind kind,
                                      hpu_dma_span_t *spans,
                                      size_t span_capacity,
                                      size_t *span_count) {
#if HPU_IT_USE_GENERATED_FHE
    unsigned count;
    if (spans == NULL || span_count == NULL) return 426;
    if (kind == HPU_CASE_CMB_KEYSWITCH ||
        kind == HPU_CASE_PERF_KEYSWITCH) {
        if (span_capacity < HPU_PROGRAM_KEYSWITCH_DMA_COUNT) return 427;
        count = fhe_generated_keyswitch_spans(spans);
        if (count != HPU_PROGRAM_KEYSWITCH_DMA_COUNT) return 428;
    } else if (kind == HPU_CASE_CMB_RELINE ||
               kind == HPU_CASE_PERF_RELIN) {
        if (span_capacity < HPU_PROGRAM_RELINEARIZATION_DMA_COUNT) return 429;
        count = fhe_generated_relin_spans(spans);
        if (count != HPU_PROGRAM_RELINEARIZATION_DMA_COUNT) return 430;
    } else if (kind == HPU_CASE_CMB_HMUL ||
               kind == HPU_CASE_PERF_CIPHERTEXT_MUL ||
               kind == HPU_CASE_APP_MINI_FHE) {
        if (span_capacity < HPU_PROGRAM_CIPHERTEXT_MULTIPLY_DMA_COUNT)
            return 431;
        count = fhe_generated_ciphertext_spans(spans);
        if (count != HPU_PROGRAM_CIPHERTEXT_MULTIPLY_DMA_COUNT) return 432;
    } else {
        return 433;
    }
    *span_count = count;
    return 0;
#else
    (void)kind;
    (void)spans;
    (void)span_capacity;
    (void)span_count;
    return 434;
#endif
}

