static void fhe_generated_span(hpu_dma_span_t *span, unsigned line,
                               unsigned lines) {
    span->line_offset = line;
    span->line_count = lines;
}

static void fhe_generated_modup(hpu_dma_span_t *spans, unsigned *dma,
                                unsigned digit) {
    static const unsigned inverse_index[FHE_DIGITS][2] = {
        {0U, 2U}, {4U, 8U},
    };
    unsigned source_first = digit * 2U;
    unsigned source;
    unsigned target;
    for (source = 0U; source < 2U; ++source) {
        unsigned basis = source_first + source;
        fhe_generated_span(&spans[(*dma)++],
                           fhe_tensor_line(FHE_LINE_TENSOR_COEFF, 2U, basis),
                           FHE_POLY_LINES);
        fhe_generated_span(&spans[(*dma)++],
                           fhe_digit_line(FHE_LINE_MODUP_COEFF, digit, basis),
                           FHE_POLY_LINES);
    }
    fhe_generated_span(&spans[(*dma)++], FHE_LINE_MOD_CTX, 1U);
    for (source = 0U; source < 2U; ++source) {
        unsigned basis = source_first + source;
        fhe_generated_span(&spans[(*dma)++],
                           fhe_tensor_line(FHE_LINE_TENSOR_COEFF, 2U, basis),
                           FHE_POLY_LINES);
        fhe_generated_span(&spans[(*dma)++],
                           fhe_broadcast_line(inverse_index[digit][source]),
                           FHE_POLY_LINES);
        fhe_generated_span(&spans[(*dma)++],
                           FHE_LINE_SCRATCH + source * FHE_POLY_LINES,
                           FHE_POLY_LINES);
    }
    for (target = 0U; target < FHE_BASIS_COUNT; ++target) {
        unsigned hat[2];
        if (target == source_first || target == source_first + 1U) continue;
        if (digit == 0U) {
            hat[0] = 1U;
            hat[1] = 3U;
        } else {
            hat[0] = target == 0U ? 5U : (target == 1U ? 6U : 7U);
            hat[1] = target == 0U ? 9U : (target == 1U ? 10U : 11U);
        }
        for (source = 0U; source < 2U; ++source) {
            fhe_generated_span(&spans[(*dma)++],
                               FHE_LINE_SCRATCH + source * FHE_POLY_LINES,
                               FHE_POLY_LINES);
            fhe_generated_span(&spans[(*dma)++], fhe_broadcast_line(hat[source]),
                               FHE_POLY_LINES);
        }
        fhe_generated_span(&spans[(*dma)++],
                           fhe_digit_line(FHE_LINE_MODUP_COEFF, digit, target),
                           FHE_POLY_LINES);
    }
}

static void fhe_generated_ntt_basis(hpu_dma_span_t *spans, unsigned *dma,
                                    unsigned input_line,
                                    unsigned output_line,
                                    unsigned basis) {
    unsigned stage;
    fhe_generated_span(&spans[(*dma)++], input_line, FHE_POLY_LINES);
    fhe_generated_span(&spans[(*dma)++], fhe_twiddle_pre_line(basis),
                       FHE_POLY_LINES);
    for (stage = 0U; stage < FHE_STAGE_COUNT; ++stage) {
        fhe_generated_span(&spans[(*dma)++],
                           fhe_twiddle_stage_line(basis, 0, stage),
                           FHE_STAGE_LINES);
    }
    fhe_generated_span(&spans[(*dma)++], output_line, FHE_POLY_LINES);
}

static void fhe_generated_intt_basis(hpu_dma_span_t *spans, unsigned *dma,
                                     unsigned input_line,
                                     unsigned output_line,
                                     unsigned basis) {
    unsigned stage;
    fhe_generated_span(&spans[(*dma)++], input_line, FHE_POLY_LINES);
    for (stage = 0U; stage < FHE_STAGE_COUNT; ++stage) {
        fhe_generated_span(&spans[(*dma)++],
                           fhe_twiddle_stage_line(basis, 1, stage),
                           FHE_STAGE_LINES);
    }
    fhe_generated_span(&spans[(*dma)++], fhe_twiddle_post_line(basis),
                       FHE_POLY_LINES);
    fhe_generated_span(&spans[(*dma)++], output_line, FHE_POLY_LINES);
}

static void fhe_generated_moddown(hpu_dma_span_t *spans, unsigned *dma,
                                  unsigned component) {
    static const unsigned groups[FHE_P_COUNT] = {12U, 17U, 22U};
    unsigned source;
    unsigned basis;
    fhe_generated_span(&spans[(*dma)++], FHE_LINE_MOD_CTX, 1U);
    for (source = 0U; source < FHE_P_COUNT; ++source) {
        fhe_generated_span(
            &spans[(*dma)++],
            fhe_acc_line(FHE_LINE_KS_COEFF, component, FHE_Q_COUNT + source),
            FHE_POLY_LINES);
        fhe_generated_span(&spans[(*dma)++],
                           fhe_broadcast_line(groups[source]),
                           FHE_POLY_LINES);
        fhe_generated_span(&spans[(*dma)++],
                           FHE_LINE_SCRATCH + source * FHE_POLY_LINES,
                           FHE_POLY_LINES);
    }
    for (basis = 0U; basis < FHE_Q_COUNT; ++basis) {
        for (source = 0U; source < FHE_P_COUNT; ++source) {
            fhe_generated_span(&spans[(*dma)++],
                               FHE_LINE_SCRATCH + source * FHE_POLY_LINES,
                               FHE_POLY_LINES);
            fhe_generated_span(&spans[(*dma)++],
                               fhe_broadcast_line(groups[source] + 1U + basis),
                               FHE_POLY_LINES);
        }
        fhe_generated_span(
            &spans[(*dma)++],
            fhe_output_line(FHE_LINE_KS_MODDOWN, component, basis),
            FHE_POLY_LINES);
    }
    fhe_generated_span(&spans[(*dma)++], FHE_LINE_MOD_CTX, 1U);
    for (basis = 0U; basis < FHE_Q_COUNT; ++basis) {
        fhe_generated_span(
            &spans[(*dma)++],
            fhe_acc_line(FHE_LINE_KS_COEFF, component, basis),
            FHE_POLY_LINES);
        fhe_generated_span(
            &spans[(*dma)++],
            fhe_output_line(FHE_LINE_KS_MODDOWN, component, basis),
            FHE_POLY_LINES);
        fhe_generated_span(&spans[(*dma)++],
                           fhe_broadcast_line(27U + basis),
                           FHE_POLY_LINES);
        fhe_generated_span(
            &spans[(*dma)++],
            fhe_output_line(FHE_LINE_KS_MODDOWN, component, basis),
            FHE_POLY_LINES);
    }
}

static unsigned fhe_generated_keyswitch_spans(hpu_dma_span_t *spans) {
    unsigned dma = 0U;
    unsigned digit;
    unsigned component;
    unsigned basis;
    for (digit = 0U; digit < FHE_DIGITS; ++digit) {
        fhe_generated_modup(spans, &dma, digit);
        fhe_generated_span(&spans[dma++], FHE_LINE_MOD_CTX, 1U);
        for (basis = 0U; basis < FHE_BASIS_COUNT; ++basis) {
            fhe_generated_ntt_basis(
                spans, &dma,
                fhe_digit_line(FHE_LINE_MODUP_COEFF, digit, basis),
                fhe_digit_line(FHE_LINE_MODUP_NTT, digit, basis), basis);
        }
        for (component = 0U; component < 2U; ++component) {
            for (basis = 0U; basis < FHE_BASIS_COUNT; ++basis) {
                fhe_generated_span(
                    &spans[dma++],
                    fhe_digit_line(FHE_LINE_MODUP_NTT, digit, basis),
                    FHE_POLY_LINES);
                fhe_generated_span(&spans[dma++],
                                   fhe_rlk_line(digit, component, basis),
                                   FHE_POLY_LINES);
                if (digit != 0U) {
                    fhe_generated_span(
                        &spans[dma++],
                        fhe_acc_line(FHE_LINE_KS_ACC_NTT, component, basis),
                        FHE_POLY_LINES);
                }
                fhe_generated_span(
                    &spans[dma++],
                    fhe_acc_line(FHE_LINE_KS_ACC_NTT, component, basis),
                    FHE_POLY_LINES);
            }
        }
    }
    fhe_generated_span(&spans[dma++], FHE_LINE_MOD_CTX, 1U);
    for (component = 0U; component < 2U; ++component) {
        for (basis = 0U; basis < FHE_BASIS_COUNT; ++basis) {
            fhe_generated_intt_basis(
                spans, &dma,
                fhe_acc_line(FHE_LINE_KS_ACC_NTT, component, basis),
                fhe_acc_line(FHE_LINE_KS_COEFF, component, basis), basis);
        }
    }
    for (component = 0U; component < 2U; ++component)
        fhe_generated_moddown(spans, &dma, component);
    fhe_generated_span(&spans[dma++], FHE_LINE_MOD_CTX, 1U);
    for (basis = 0U; basis < FHE_Q_COUNT; ++basis) {
        fhe_generated_span(
            &spans[dma++],
            fhe_output_line(FHE_LINE_KS_MODDOWN, 0U, basis),
            FHE_POLY_LINES);
        fhe_generated_span(
            &spans[dma++],
            fhe_tensor_line(FHE_LINE_TENSOR_COEFF, 0U, basis),
            FHE_POLY_LINES);
        fhe_generated_span(
            &spans[dma++],
            fhe_output_line(FHE_LINE_CIPHER_OUT, 0U, basis),
            FHE_POLY_LINES);
    }
    return dma;
}

static unsigned fhe_generated_relin_spans(hpu_dma_span_t *spans) {
    unsigned dma = fhe_generated_keyswitch_spans(spans);
    unsigned basis;
    fhe_generated_span(&spans[dma++], FHE_LINE_MOD_CTX, 1U);
    for (basis = 0U; basis < FHE_Q_COUNT; ++basis) {
        fhe_generated_span(
            &spans[dma++],
            fhe_tensor_line(FHE_LINE_TENSOR_COEFF, 1U, basis),
            FHE_POLY_LINES);
        fhe_generated_span(
            &spans[dma++],
            fhe_output_line(FHE_LINE_KS_MODDOWN, 1U, basis),
            FHE_POLY_LINES);
        fhe_generated_span(
            &spans[dma++],
            fhe_output_line(FHE_LINE_CIPHER_OUT, 1U, basis),
            FHE_POLY_LINES);
    }
    return dma;
}

static unsigned fhe_generated_ciphertext_spans(hpu_dma_span_t *spans) {
    unsigned dma = 0U;
    unsigned component;
    unsigned input;
    unsigned basis;
    fhe_generated_span(&spans[dma++], FHE_LINE_MOD_CTX, 1U);
    for (component = 0U; component < 2U; ++component) {
        for (basis = 0U; basis < FHE_Q_COUNT; ++basis) {
            fhe_generated_ntt_basis(
                spans, &dma, fhe_ct_line(0U, component, basis),
                fhe_input_ntt_line(component, basis), basis);
        }
    }
    fhe_generated_span(&spans[dma++], FHE_LINE_MOD_CTX, 1U);
    for (component = 0U; component < 2U; ++component) {
        input = 2U + component;
        for (basis = 0U; basis < FHE_Q_COUNT; ++basis) {
            fhe_generated_ntt_basis(
                spans, &dma, fhe_ct_line(1U, component, basis),
                fhe_input_ntt_line(input, basis), basis);
        }
    }
    fhe_generated_span(&spans[dma++], FHE_LINE_MOD_CTX, 1U);
    for (basis = 0U; basis < FHE_Q_COUNT; ++basis) {
#define FHE_GEN_INPUT(index_) fhe_input_ntt_line((index_), basis)
#define FHE_GEN_TENSOR(index_) \
        fhe_tensor_line(FHE_LINE_TENSOR_NTT, (index_), basis)
        fhe_generated_span(&spans[dma++], FHE_GEN_INPUT(0U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_INPUT(2U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_TENSOR(0U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_INPUT(0U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_INPUT(3U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_INPUT(1U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_INPUT(2U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_TENSOR(1U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_INPUT(1U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_INPUT(3U), FHE_POLY_LINES);
        fhe_generated_span(&spans[dma++], FHE_GEN_TENSOR(2U), FHE_POLY_LINES);
#undef FHE_GEN_INPUT
#undef FHE_GEN_TENSOR
    }
    fhe_generated_span(&spans[dma++], FHE_LINE_MOD_CTX, 1U);
    for (component = 0U; component < 3U; ++component) {
        for (basis = 0U; basis < FHE_Q_COUNT; ++basis) {
            fhe_generated_intt_basis(
                spans, &dma,
                fhe_tensor_line(FHE_LINE_TENSOR_NTT, component, basis),
                fhe_tensor_line(FHE_LINE_TENSOR_COEFF, component, basis),
                basis);
        }
    }
    dma += fhe_generated_relin_spans(spans + dma);
    return dma;
}
