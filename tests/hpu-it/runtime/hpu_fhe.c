static int fhe_issue_program(fhe_program_kind program) {
#if HPU_IT_USE_GENERATED_FHE
    hpu_dma_span_t spans[HPU_PROGRAM_CIPHERTEXT_MULTIPLY_DMA_COUNT];
    unsigned count;
    int rc;
    if (program == FHE_PROGRAM_KEYSWITCH) {
        count = fhe_generated_keyswitch_spans(spans);
        if (count != HPU_PROGRAM_KEYSWITCH_DMA_COUNT) return 423;
        rc = hpu_program_keyswitch(spans, count);
    } else if (program == FHE_PROGRAM_RELIN) {
        count = fhe_generated_relin_spans(spans);
        if (count != HPU_PROGRAM_RELINEARIZATION_DMA_COUNT) return 424;
        rc = hpu_program_relinearization(spans, count);
    } else {
        count = fhe_generated_ciphertext_spans(spans);
        if (count != HPU_PROGRAM_CIPHERTEXT_MULTIPLY_DMA_COUNT) return 425;
        rc = hpu_program_ciphertext_multiply(spans, count);
    }
    if (rc == 0) rc = fhe_wait_terminal_sync();
    return rc;
#else
    int rc = fhe_dload(4U, FHE_LINE_MOD_CTX, 1U, 1);
    if (rc == 0 && program == FHE_PROGRAM_CIPHERTEXT_MUL) {
        rc = fhe_issue_ciphertext_prefix();
    }
    if (rc == 0) rc = fhe_issue_keyswitch(program);
    if (rc == 0) hpu_pfree(4U);
    if (rc == 0) {
        /* The entire composite program has exactly one, terminal PSYNC. */
        hpu_psync();
        rc = fhe_wait_terminal_sync();
    }
    return rc;
#endif
}
