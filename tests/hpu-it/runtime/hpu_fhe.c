static int fhe_dload(unsigned object, unsigned line, unsigned lines,
                     int mod_table) {
    hpu_dma_span span;
    if (lines == 0U || line > HPU_IT_MEM_LINES ||
        lines > HPU_IT_MEM_LINES - line) {
        return 413;
    }
    span.line_offset = line;
    span.line_count = lines;
    if (mod_table) {
        if (object != 4U || lines != 1U) return 414;
        hpu_dload_mod_p4(span);
        return 0;
    }
    switch (object) {
    case 0U: hpu_dload_poly_p0(span); break;
    case 1U: hpu_dload_poly_p1(span); break;
    case 2U: hpu_dload_poly_p2(span); break;
    case 3U: hpu_dload_poly_p3(span); break;
    case 4U: hpu_dload_poly_p4(span); break;
    case 5U: hpu_dload_poly_p5(span); break;
    case 6U: hpu_dload_poly_p6(span); break;
    case 7U: hpu_dload_poly_p7(span); break;
    default: return 415;
    }
    return 0;
}

